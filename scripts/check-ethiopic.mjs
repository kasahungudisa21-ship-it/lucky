import { readFile, readdir } from "node:fs/promises";
import path from "node:path";

const isEthiopic = (ch) => {
  const cp = ch.codePointAt(0);
  return cp >= 0x1200 && cp <= 0x137f;
};

const files = [];
const skip = new Set(["node_modules", ".next", ".git", "node_modules.stale"]);
async function collect(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (skip.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await collect(full);
    else if (/\.(ts|tsx|mjs|json|prisma|css|html|md)$/.test(entry.name)) files.push(full);
  }
}
await collect(".");

// ui.ts is machine-generated by the translation endpoint, so its syllables are
// the reference set. Any hand-written Ethiopic token that is a one-syllable
// deletion of a reference token is corruption, not a different word.
const ui = await readFile("src/lib/ui.ts", "utf8");
const reference = new Set();
for (const run of ui.match(new RegExp("[\\u1200-\\u137f]+", "g")) ?? []) reference.add(run);
const referenceSyllables = new Map();
for (const token of reference) {
  for (let i = 0; i < token.length; i += 1) {
    const deleted = token.slice(0, i) + token.slice(i + 1);
    if (deleted.length >= 2) referenceSyllables.set(deleted, token);
  }
}

let findings = 0;
for (const file of files) {
  // ui.ts is the reference, and the Amharic tooling quotes example syllables in
  // its own comments, so neither is a candidate for hand-typed corruption.
  if (file.endsWith(path.join("src", "lib", "ui.ts")) || /i18n|amharic/.test(path.basename(file)))
    continue;
  const text = await readFile(file, "utf8");
  const tokens = text.match(new RegExp("[\\u1200-\\u137f]+", "g")) ?? [];
  for (const token of new Set(tokens)) {
    const escaped = [...token].map((c) => c.codePointAt(0).toString(16)).join(" ");
    const status = reference.has(token) ? "matches ui.ts" : referenceSyllables.get(token) ? "SUSPECT deletion of " + [...referenceSyllables.get(token)].map((c) => c.codePointAt(0).toString(16)).join(" ") : "unreferenced";
    if (status !== "matches ui.ts") {
      findings += 1;
      console.log(file.padEnd(34), escaped.padEnd(30), status);
    }
  }
}
console.log(findings ? `${findings} token(s) to review` : "every hand-written Ethiopic token matches ui.ts");
